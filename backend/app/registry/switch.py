"""Point a project at the registry's fixed build of a library (REG.1).

A dependency finding whose advisory has no fixed release, and for which the registry holds a proved build (or a recipe
to make one), is fixed by switching the project to that build: the manifest pins the build's version from the index
called "whitehats", and the lockfile is regenerated by uv against the registry itself, so its wheel URL, sha256 and
size are the registry's own. WhiteHats works the new files out exactly; Fix Factory writes them, and the proof (the
dependency scanner, with the registry's statements) and CI judge them. Only uv projects are handled.
"""

from __future__ import annotations

import hashlib
import os
import secrets
import subprocess
import tempfile
import tomllib
from dataclasses import dataclass
from pathlib import Path, PurePosixPath

from sqlalchemy import select
from sqlalchemy.orm import Session

from ..config import settings
from ..db import utcnow
from ..models import RegistryPackage, RegistryToken
from .build import BuildRefused, build, normalized
from .recipes import RECIPES, Recipe

INDEX = "whitehats"
LOCK_TIMEOUT_S = 120


class NoSwitch(Exception):
    """The registry cannot fix this finding; the message says why, for the person it goes to instead."""


@dataclass(frozen=True)
class Target:
    """What a dependency finding is about: the package as the lockfile pins it, and the advisory."""

    name: str
    version: str
    advisory: str
    manifest_dir: str  # the folder holding pyproject.toml and uv.lock, relative to the repository


def target(suspect: dict) -> Target | None:
    evidence = suspect.get("evidence") or {}
    pinned = str(evidence.get("package") or "")
    if suspect.get("engine") != "osv-scanner" or "@" not in pinned:
        return None
    name, version = pinned.split("@", 1)
    path = PurePosixPath(str(evidence.get("path") or ""))
    if path.name != "uv.lock":
        return None
    return Target(name, version, str(suspect.get("rule_id") or ""), str(path.parent))


def recipe_for(found: Target) -> Recipe | None:
    return next((r for r in RECIPES.values() if normalized(r.name) == found.name and r.upstream_version == found.version
                 and found.advisory in r.advisories), None)


def proved_build(db: Session, org_id: int, found: Target) -> RegistryPackage | None:
    rows = db.scalars(select(RegistryPackage).where(
        RegistryPackage.org_id == org_id, RegistryPackage.status == "proved",
        RegistryPackage.upstream_version == found.version).order_by(RegistryPackage.id.desc())).all()
    return next((row for row in rows if normalized(row.name) == found.name and found.advisory in row.advisories), None)


def ensure_build(db: Session, org_id: int, found: Target) -> RegistryPackage:
    """The registry's proved build for this finding, made now from its recipe when there is none yet."""
    row = proved_build(db, org_id, found)
    if row is not None:
        return row
    recipe = recipe_for(found)
    if recipe is None:
        raise NoSwitch(f"No fixed release of {found.name} {found.version} exists for {found.advisory}, and the WhiteHats "
                       "Registry has no fixed build of it. A person has to decide: move to another library, or accept "
                       "the risk with a reason.")
    try:
        return build(db, org_id, recipe, by="WhiteHats")
    except BuildRefused as exc:
        raise NoSwitch(f"WhiteHats could not make a proved fixed build of {found.name}: {exc}") from exc


def _requirement_name(spec: str) -> str:
    """The project name a requirement starts with ("PyPDF2==3.0.1" is "PyPDF2")."""
    end = next((at for at, char in enumerate(spec) if char in "=<>!~[; "), len(spec))
    return spec[:end]


def index_url() -> str:
    return settings.public_url.rstrip("/") + "/api/registry/simple/"


def pinned_manifest(text: str, name: str, upstream: str, version: str) -> str:
    """The pyproject.toml with the library pinned to the fixed build from the registry's index."""
    project = tomllib.loads(text)
    deps = project.get("project", {}).get("dependencies", [])
    spec = next((d for d in deps if normalized(_requirement_name(d)) == name), None)
    if spec is None or f"=={upstream}" not in spec:
        raise NoSwitch(f"The manifest does not pin {name} to {upstream} exactly, so WhiteHats will not change it.")
    out = text.replace(f'"{spec}"', f'"{spec.replace(f"=={upstream}", f"=={version}")}"', 1)
    uv = project.get("tool", {}).get("uv", {})
    if not any(index.get("name") == INDEX for index in uv.get("index", [])):
        out = out.rstrip("\n") + f'\n\n[[tool.uv.index]]\nname = "{INDEX}"\nurl = "{index_url()}"\nexplicit = true\n'
    if name not in uv.get("sources", {}):
        if "sources" in uv:
            raise NoSwitch("The manifest already names sources; WhiteHats will not merge its own into them.")
        out = out.rstrip("\n") + f'\n\n[tool.uv.sources]\n{name} = {{ index = "{INDEX}" }}\n'
    return out


def relocked(db: Session, org_id: int, manifest: str, lock: str | None) -> str:
    """The lockfile uv writes for this manifest, reading the registry with a token made for this one run."""
    token = "whr_" + secrets.token_urlsafe(32)
    row = RegistryToken(org_id=org_id, name="WhiteHats (regenerating a lockfile)", hint=token[-4:],
                        token_hash=hashlib.sha256(token.encode()).hexdigest(), created_by="WhiteHats")
    db.add(row)
    db.commit()
    try:
        with tempfile.TemporaryDirectory(prefix="wh-relock-") as work:
            folder = Path(work)
            (folder / "pyproject.toml").write_text(manifest)
            if lock is not None:
                (folder / "uv.lock").write_text(lock)
            env = {**os.environ, "UV_INDEX_WHITEHATS_USERNAME": "token", "UV_INDEX_WHITEHATS_PASSWORD": token,
                   "UV_NO_CONFIG": "1", "UV_CACHE_DIR": str(folder / ".cache")}
            try:
                done = subprocess.run(["uv", "lock", "--quiet"], cwd=folder, env=env, capture_output=True, text=True,
                                      timeout=LOCK_TIMEOUT_S, check=False)
            except (FileNotFoundError, subprocess.TimeoutExpired) as exc:
                raise NoSwitch(f"uv could not regenerate the lockfile: {exc}") from exc
            if done.returncode:
                raise NoSwitch(f"uv could not regenerate the lockfile: {done.stderr.strip()[-300:]}")
            return (folder / "uv.lock").read_text()
    finally:
        row.revoked_at = utcnow()
        db.commit()


def files(db: Session, org_id: int, found: Target, build_row: RegistryPackage, manifest: str, lock: str | None) -> dict[str, str]:
    """The project's new pyproject.toml and uv.lock, by their paths in the repository."""
    new_manifest = pinned_manifest(manifest, found.name, found.version, build_row.version)
    base = "" if found.manifest_dir in ("", ".") else f"{found.manifest_dir}/"
    return {f"{base}pyproject.toml": new_manifest, f"{base}uv.lock": relocked(db, org_id, new_manifest, lock)}
